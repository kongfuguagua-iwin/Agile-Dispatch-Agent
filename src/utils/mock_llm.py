# -*- coding: utf-8 -*-
"""
Mock LLM Implementation
Returns structured JSON based on prompt keywords
"""

import json
import re
from typing import Dict, Any, Optional


class MockLLM:
    """
    Mock LLM that returns valid JSON based on prompt keywords
    
    Allows parsing logic to execute without API key
    """
    
    def __init__(self):
        """Initialize Mock LLM"""
        self.call_count = 0
    
    def chat(
        self,
        prompt: str,
        system_prompt: Optional[str] = None
    ) -> str:
        """
        Generate response based on prompt keywords
        
        Args:
            prompt: User prompt
            system_prompt: System prompt (ignored in mock)
            
        Returns:
            JSON string response
        """
        self.call_count += 1
        prompt_lower = prompt.lower()
        
        # Problem formulation request
        if 'optimization problem' in prompt_lower or 'formulation' in prompt_lower:
            return self._generate_problem_formulation(prompt)
        
        # Logical evaluation request
        if 'logical coherence' in prompt_lower or 'evaluate' in prompt_lower:
            return self._generate_logical_evaluation(prompt)
        
        # Feature analysis request
        if 'feature' in prompt_lower and 'analysis' in prompt_lower:
            return self._generate_feature_analysis(prompt)
        
        # Default: return simple JSON
        return json.dumps({
            "response": "Mock LLM response",
            "call_count": self.call_count
        })
    
    def _generate_problem_formulation(self, prompt: str) -> str:
        """Generate optimization problem formulation"""
        # Extract context from prompt
        has_load = 'load' in prompt.lower()
        has_generation = 'generation' in prompt.lower() or 'gen' in prompt.lower()
        has_constraint = 'constraint' in prompt.lower()
        
        # Build problem
        variables = []
        constraints = []
        
        if has_generation:
            # Generator dispatch problem
            for i in range(5):
                variables.append({
                    "name": f"gen_{i}",
                    "type": "continuous",
                    "lower_bound": 0.0,
                    "upper_bound": 100.0,
                    "description": f"Generator {i} power output"
                })
            
            objective = "min sum(gen_costs[i] * gen_{i} for i in range(5))"
            constraints.append("sum(gen_{i} for i in range(5)) >= total_load")
            constraints.append("gen_{i} >= 0 for i in range(5)")
            constraints.append("gen_{i} <= 100 for i in range(5)")
        else:
            # Generic problem
            variables.append({
                "name": "x",
                "type": "continuous",
                "lower_bound": 0.0,
                "upper_bound": 100.0,
                "description": "Decision variable"
            })
            objective = "min x"
            constraints.append("x >= 0")
            constraints.append("x <= 100")
        
        problem = {
            "objective": objective,
            "constraints": constraints,
            "variables": variables,
            "is_minimization": True,
            "modeling_rationale": "Generated by Mock LLM based on prompt analysis"
        }
        
        return json.dumps(problem, indent=2)
    
    def _generate_logical_evaluation(self, prompt: str) -> str:
        """Generate logical coherence evaluation"""
        # Extract solution info from prompt
        has_feasible = 'feasible' in prompt.lower()
        has_variables = 'variable' in prompt.lower() or 'decision' in prompt.lower()
        
        # Score based on keywords
        score = 0.7  # Default
        if has_feasible:
            score = 0.85
        if has_variables:
            score = min(1.0, score + 0.1)
        
        evaluation = {
            "rationality": score,
            "safety": score - 0.05,
            "sustainability": score - 0.1,
            "overall_score": score,
            "reasoning": "Solution appears logically coherent based on structure analysis"
        }
        
        return json.dumps(evaluation, indent=2)
    
    def _generate_feature_analysis(self, prompt: str) -> str:
        """Generate feature analysis"""
        # Detect problem characteristics
        has_nonlinear = 'sin' in prompt.lower() or 'cos' in prompt.lower() or '**' in prompt.lower()
        has_integer = 'integer' in prompt.lower() or 'binary' in prompt.lower()
        has_constraint = 'constraint' in prompt.lower()
        
        features = {
            "non_convexity_score": 0.3 if has_nonlinear else 0.1,
            "non_linearity_score": 0.5 if has_nonlinear else 0.2,
            "constraint_stiffness": 0.4 if has_constraint else 0.2,
            "discreteness_score": 0.8 if has_integer else 0.0,
            "scale_score": 0.3
        }
        
        return json.dumps(features, indent=2)

